import type { StylePreset } from '../types/settings';
import type { RenderDocumentResult } from '../types/ir';
import { parseMarkdownToIr } from '../parser/markdownParser';
import { renderIrBlocksToHtml } from './blockRenderer';
import { escapeHtmlCommentText, escapeHtmlText } from './inlineFlattener';

export const PREVIEW_SHELL_STYLESHEET = `    /* 仅用于浏览器本地预览居中限宽，严禁对 section / p / span 设置任何默认样式 */
    html, body {
      margin: 0;
      padding: 0;
      background-color: #f5f5f5;
    }
    .inline-html-preview-shell {
      max-width: 677px;
      margin: 24px auto;
      padding: 32px 24px;
      background-color: #ffffff;
      box-sizing: border-box;
      box-shadow: 0 2px 12px rgba(0, 0, 0, 0.06);
    }`;

/**
 * 将已渲染的正文块序列包裹为完整可浏览的 UTF-8 HTML5 文档
 */
export function wrapFullHtmlDocument(
  sectionsHtml: string,
  noteTitle: string,
  presetName: string,
): string {
  const safeTitle = escapeHtmlText(noteTitle || 'Untitled');
  const safePreset = escapeHtmlCommentText(presetName || '默认预设');

  return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${safeTitle}</title>
  <style>
${PREVIEW_SHELL_STYLESHEET}
  </style>
</head>
<body>
  <div class="inline-html-preview-shell">
<!-- Generated by Obsidian Plugin: Inline HTML | Preset: ${safePreset} -->
${sectionsHtml}
  </div>
</body>
</html>
`;
}

/**
 * 端到端转换入口：Markdown 原文 + 样式预设 -> 正文 HTML 片段 + 完整 HTML5 文档 + 警告统计
 */
export function convertMarkdownToInlineHtml(
  markdown: string,
  preset: StylePreset,
  noteTitle = 'Untitled',
): RenderDocumentResult {
  const irBlocks = parseMarkdownToIr(markdown);
  const { sectionsHtml, warnings } = renderIrBlocksToHtml(irBlocks, preset);
  const fullHtml = wrapFullHtmlDocument(sectionsHtml, noteTitle, preset.name);

  return {
    sectionsHtml,
    fullHtml,
    warnings,
  };
}
